#!/usr/bin/env node
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Writes the event coverage table.
 *
 * `docs/event-coverage.md` is evidence, and evidence that is maintained by hand
 * stops being evidence. It is generated from the source, and
 * `event-coverage.test.ts` fails if the committed file no longer matches — so
 * wiring an event and forgetting the table is a red test, not a stale document.
 *
 *   node scripts/event-coverage.mjs          # write
 *   node scripts/event-coverage.mjs --check  # verify only
 */

const root = fileURLToPath(new URL('..', import.meta.url));

const SKIP = new Set(['__tests__', '__fixtures__', 'node_modules']);

export function sourceFiles(dir = join(root, 'src'), found = []) {
  for (const entry of readdirSync(dir)) {
    if (SKIP.has(entry)) continue;

    const full = join(dir, entry);
    if (statSync(full).isDirectory()) sourceFiles(full, found);
    else if (/\.tsx?$/.test(entry)) {
      found.push({ path: relative(root, full), text: readFileSync(full, 'utf8') });
    }
  }
  return found;
}

const events = readFileSync(join(root, 'src/platform/analytics/events.ts'), 'utf8');
const names = [...events.matchAll(/^\s{2}'([a-z_]+)',$/gm)].map((match) => match[1]);

const files = sourceFiles().filter(
  (file) => !file.path.endsWith('src/platform/analytics/coverage.ts')
);

const rows = names.map((event) => {
  const sites = files
    .filter((file) => new RegExp(`track\\(\\s*['"\`]${event}['"\`]`).test(file.text))
    .map((file) => file.path)
    .sort();
  return { event, sites };
});

const table = [
  '| event | sent from |',
  '|---|---|',
  ...rows.map((row) => `| \`${row.event}\` | ${row.sites.map((s) => `\`${s}\``).join('<br>')} |`),
].join('\n');

const document = `# Event coverage

Generated by \`node scripts/event-coverage.mjs\`. Do not edit by hand —
\`src/platform/analytics/__tests__/event-coverage.test.ts\` fails when this file
and the source disagree.

Every event declared in \`src/platform/analytics/events.ts\` must appear here
with at least one call site, or be removed from the taxonomy. An event nobody
sends is a dashboard that reads zero and a decision made on it.

${table}

## What the impression numbers mean

\`seed_impression\` counts a card **rendered into a list the reader opened**, not
one verified to have crossed the viewport: the home and topic screens are
\`ScrollView\`s, which have no viewability callback. The count is an upper bound,
biased in one direction, and deduplicated per seed per placement per launch.
See \`src/platform/analytics/impression.ts\`.
`;

const target = join(root, 'docs/event-coverage.md');
const missing = rows.filter((row) => !row.sites.length).map((row) => row.event);

if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8');
  if (current !== document) {
    console.error('docs/event-coverage.md is out of date — run node scripts/event-coverage.mjs');
    process.exit(1);
  }
  if (missing.length) {
    console.error(`events declared but never sent: ${missing.join(', ')}`);
    process.exit(1);
  }
  console.log(`event coverage current — ${rows.length} events, all wired`);
} else {
  writeFileSync(target, document);
  console.log(`wrote docs/event-coverage.md — ${rows.length} events, ${missing.length} unwired`);
}
